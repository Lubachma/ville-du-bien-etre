import { readFile, writeFile, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = name => readFile(path.join(root, name), 'utf8');
const sources = (await readdir(path.join(root, 'src'))).filter(n => /^\d+.*\.js$/.test(n)).sort();
const application = sources.filter(n => n !== '70-install.js');
const app = '/* Generated by npm run build. Edit src/ instead. */\n(() => {\n\'use strict\';\n'
  + (await Promise.all(application.map(async name => `\n/* ---- ${name} ---- */\n${await read('src/' + name)}`))).join('\n')
  + '\n})();\n' + await read('src/70-install.js');
await writeFile(path.join(root, 'app.js'), app);

const assets = ['index.html', 'app.js', 'styles.css', 'styles-activities.css', 'styles-features.css', 'manifest.webmanifest'];
for (const folder of ['icons', 'fonts']) {
  for (const name of (await readdir(path.join(root, folder))).sort()) {
    if (/\.(png|woff2)$/.test(name)) assets.push(`${folder}/${name}`);
  }
}
const hash = createHash('sha256');
for (const name of assets) hash.update(name).update(await readFile(path.join(root, name)));
const template = await read('scripts/sw-template.js');
hash.update(template);
const version = hash.digest('hex').slice(0, 12);
const sw = template.replace('__VERSION__', version).replace('__ASSETS__', JSON.stringify(assets));
await writeFile(path.join(root, 'sw.js'), sw);
console.log(`Built ${sources.length} source files; offline version ${version} (${assets.length} assets).`);
